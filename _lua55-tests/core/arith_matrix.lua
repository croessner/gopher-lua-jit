end

local function check_unary(op, constant)
  local want = split(expected_unary[op])
  local bad = {}
  for i, a in ipairs(operands) do
    local got
    if constant then
      local f = load("return " .. op .. "(" .. a .. ")")
      got = f and render(pcall(f)) or "does not compile"
    else
      got = render(pcall(load("local a = ... return " .. op .. "a"), values[i]))
    end
    if not matches(op, got, want[i]) then
      bad[#bad + 1] = op .. a .. " = " .. got .. " (expected " .. want[i] .. ")"
    end
  end
  report(bad)
end

