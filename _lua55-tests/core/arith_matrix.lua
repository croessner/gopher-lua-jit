    local f = load("local b = ... return (" .. a .. ") " .. op .. " b")
    for j, b in ipairs(operands) do
      local got = f and render(pcall(f, values[j])) or "does not compile"
      if not matches(op, got, want[j]) then
        bad[#bad + 1] = a .. " " .. op .. " " .. b .. " = " .. got .. " (expected " .. want[j] .. ")"
      end
    end
