local function render(ok, v)
  if not ok then return "E" end
  if v ~= v then return "nan" end
  local s = tostring(v)
  if s == "-0.0" then s = "0.0" end
  return s
end

-- reports whether a rendered result matches an expected cell
local function matches(op, got, want)
  if want == "skip" or got == want then return true end
  if op == "^" then
    -- numerals are evaluated by the compiler; tonumber is a library matter
    local gf, wf = load("return " .. got), load("return " .. want)
    local g, w = gf and gf(), wf and wf()
    if type(g) == "number" and type(w) == "number" and w ~= 0 and g - g == 0 and w - w == 0 then
      local d = (g - w) / w
      return d < 1e-13 and d > -1e-13
    end
  end
  return false
end

local function split(row)
  local out = {}
  for w in row:gmatch("%S+") do out[#out + 1] = w end
  return out
end

local values = {}
for i, src in ipairs(operands) do values[i] = load("return " .. src)() end

-- fails with a list of the deviating cells, if any
local function report(bad)
  if #bad > 0 then
    local shown = {}
    for i = 1, #bad do
      if i > 8 then break end
      shown[i] = bad[i]
    end
    error(#bad .. " deviations: " .. table.concat(shown, "; "), 0)
  end
end

local function check_runtime(op)
  local f = load("local a, b = ... return a " .. op .. " b")
  local bad = {}
  for i, a in ipairs(operands) do
    local want = split(expected[op][i])
    for j, b in ipairs(operands) do
      local got = render(pcall(f, values[i], values[j]))
      if not matches(op, got, want[j]) then
        bad[#bad + 1] = a .. " " .. op .. " " .. b .. " = " .. got .. " (expected " .. want[j] .. ")"
      end
    end
  end
  report(bad)
end

local function check_constant(op)
  local bad = {}
  for i, a in ipairs(operands) do
    local want = split(expected[op][i])
    for j, b in ipairs(operands) do
      local f = load("return (" .. a .. ") " .. op .. " (" .. b .. ")")
      local got = f and render(pcall(f)) or "does not compile"
      if not matches(op, got, want[j]) then
        bad[#bad + 1] = a .. " " .. op .. " " .. b .. " = " .. got .. " (expected " .. want[j] .. ")"
      end
    end
  end
  report(bad)
end

-- the right operand is a constant, the left one a run-time value
local function check_right_constant(op)
  local bad = {}
  for j, b in ipairs(operands) do
    local f = load("local a = ... return a " .. op .. " (" .. b .. ")")
    for i, a in ipairs(operands) do
      local want = split(expected[op][i])[j]
      local got = f and render(pcall(f, values[i])) or "does not compile"
      if not matches(op, got, want) then
        bad[#bad + 1] = a .. " " .. op .. " " .. b .. " = " .. got .. " (expected " .. want .. ")"
      end
    end
  end
  report(bad)
end

-- the left operand is a constant, the right one a run-time value
local function check_left_constant(op)
