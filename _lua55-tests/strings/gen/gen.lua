-- Generator for the conformance scripts: reads a case file and prints a
-- test script whose expectations come from the interpreter running this
-- generator (the reference lua5.5). Run it from _lua55-tests/strings:
--   lua5.5 gen/gen.lua gen/NAME.cases > NAME.lua
-- Every case line is evaluated on its own (after the statements seen so
-- far), so a case must not depend on side effects of an earlier case line.
-- Case file syntax:
--   plain line   : a Lua expression; its results (or its error) are recorded
--   "! stmt"     : a statement copied verbatim (and visible to later lines)
--   "-- text"    : comment copied verbatim; empty lines are kept
local prelude = [[
local function norm(msg)
  msg = tostring(msg)
  msg = msg:gsub("^[^\n]-:%d+: ", "")
  msg = msg:gsub("to '[^']*'", "to '?'")
  return msg
end
local function q(v)
  local t = type(v)
  if t == "string" then
    v = v:gsub("\\", "\\\\")
    v = v:gsub("[^\32-\126]", function(c) return "\\" .. c:byte() .. ";" end)
    return '"' .. v .. '"'
  elseif t == "number" then
    if v ~= v then return "nan" end
    return tostring(v)
  elseif t == "nil" or t == "boolean" then
    return tostring(v)
  end
  return t
end
local function d(...)
  local a, t = {...}, {}
  for i = 1, select("#", ...) do t[i] = q(a[i]) end
  return table.concat(t, " ")
end
local state = {checks = 0}
local function eq(got, expected)
  state.checks = state.checks + 1
  if got ~= expected then
    error("check #" .. state.checks .. ": expected " .. expected .. ", got " .. got, 2)
  end
end
local function err(expected, f)
  state.checks = state.checks + 1
  local ok, msg = pcall(f)
  if ok then
    error("check #" .. state.checks .. ": expected error " .. expected .. ", got success", 2)
  end
  msg = norm(msg)
  if msg ~= expected then
    error("check #" .. state.checks .. ": expected error " .. expected .. ", got " .. msg, 2)
  end
end
]]
local env_prefix = prelude
local function lit(s)  -- Lua literal for a string
  return string.format("%q", s)
end
local name = arg[1]:match("([^/]+)%.cases$")
io.write("-- Generated by gen/gen.lua from gen/", name, ".cases with the reference\n")
io.write("-- interpreter (lua5.5 gen/gen.lua gen/", name, ".cases > ", name, ".lua); do not edit by hand.\n\n")
io.write(prelude)
local count = 0
for line in io.lines(arg[1]) do
  if line:sub(1, 2) == "--" or line == "" then
    io.write(line, "\n")
  elseif line:sub(1, 2) == "! " then
    local stmt = line:sub(3)
    env_prefix = env_prefix .. stmt .. "\n"
    io.write(stmt, "\n")
  else
    local chunk, cerr = load(env_prefix .. "\nreturn (function() return d(" .. line .. ") end)", "=case")
    if not chunk then error("bad case: " .. line .. ": " .. cerr) end
    local f = chunk()
    local ok, res = pcall(f)
    count = count + 1
    if ok then
      io.write("eq(d(", line, "), ", lit(res), ")\n")
    else
      local msg = tostring(res):gsub("^[^\n]-:%d+: ", ""):gsub("to '[^']*'", "to '?'")
      io.write("err(", lit(msg), ", function() return ", line, " end)\n")
    end
  end
end
io.write("\nassert(state.checks == ", count, ")\n")
